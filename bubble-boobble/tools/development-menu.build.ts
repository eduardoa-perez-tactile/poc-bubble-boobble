import { defineBuildStep } from '@gameengine/tools';

const path = 'src/desktop/build-flags.ts';
const source = (enabled: boolean, web = false) => `/** Generated by tools/development-menu.build.ts; safe default for direct cooks. */\nexport const DEVELOPMENT_BUILD = ${enabled};\nexport const WEB_BUILD = ${web};\n`;
/** Cook disables the engine DEV constant even for dev players. Bake the actual build config. */
export const developmentMenu = defineBuildStep({
  name: 'development-menu',
  description: 'Sets development menu capability from the actual player build configuration.',
  bucket: 'first',
  run(ctx) { ctx.write(path, source(ctx.build.config !== 'release' && ctx.build.platform !== 'web', ctx.build.platform === 'web')); },
});
export const resetDevelopmentMenu = defineBuildStep({
  name: 'reset-development-menu',
  description: 'Restores release-safe defaults after the build has captured its capability.',
  phase: 'post-build',
  bucket: 'last',
  run(ctx) { ctx.write(path, source(false)); },
});
export const resetFailedDevelopmentMenu = defineBuildStep({
  name: 'reset-failed-development-menu',
  description: 'Restores release-safe defaults after a failed build.',
  phase: 'build-failed',
  bucket: 'last',
  run(ctx) { ctx.write(path, source(false)); },
});
